import { expect, test } from '@playwright/test'

test('演示模式隔离、中文组合输入和同名跨平台草稿', async ({ page }) => {
  await page.route('**/api/v1/session', route => route.fulfill({ status: 401, json: { error: { code: 'unauthorized', message: 'test' } } }))
  await page.goto('/')
  await page.getByRole('button', { name: '打开界面演示' }).click()
  await expect(page.locator('.demo-banner')).toContainText('合成内容')
  await expect(page.locator('.composer textarea')).toBeVisible()
  await page.screenshot({ path: 'test-results/demo-desktop.png' })
  const input = page.locator('.composer textarea')
  await input.fill('中文组合输入不能误发')
  const before = await page.locator('[data-message-id^="local-"]').count()
  await input.dispatchEvent('compositionstart')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', keyCode: 229, isComposing: true })
  await expect(input).toHaveValue('中文组合输入不能误发')
  expect(await page.locator('[data-message-id^="local-"]').count()).toBe(before)
  await input.dispatchEvent('compositionend', { data: '发' })
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', keyCode: 13 })
  await expect(input).toHaveValue('中文组合输入不能误发')
  await page.waitForTimeout(150)
  await input.press('Enter')
  await expect(input).toHaveValue('')
  await expect(page.locator('[data-message-id^="local-"]')).toHaveCount(before + 1)
  const wx = page.locator('.conversation-item').filter({ has: page.locator('.conversation-line strong').filter({ hasText: /^林野$/ }) }).filter({ hasText: '生活 · 示例账号' })
  const qq = page.locator('.conversation-item').filter({ has: page.locator('.conversation-line strong').filter({ hasText: /^林野$/ }) }).filter({ hasText: '兴趣 · 示例账号' })
  await wx.click()
  await input.fill('微信独立草稿')
  await qq.click()
  await expect(input).toHaveValue('')
  await input.fill('QQ 独立草稿')
  await wx.click()
  await expect(input).toHaveValue('微信独立草稿')
  await qq.click()
  await expect(input).toHaveValue('QQ 独立草稿')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '返回会话列表' }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await qq.click()
  await expect(input).toHaveValue('QQ 独立草稿')
  await page.screenshot({ path: 'test-results/demo-mobile-dark.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: '退出演示' }).click()
  await expect(page.getByLabel('SnSBox 管理密码')).toBeVisible()
  await page.getByRole('button', { name: '打开界面演示' }).click()
  await expect(input).toHaveValue('')
  await expect(page.locator('[data-message-id^="local-"]')).toHaveCount(0)
})

test('真实接口模式的字节上限、能力提示与不确定发送不自动重试', async ({ page }) => {
  let sends = 0
  let histories = 0
  const account = { id: 'test-wx', platform: 'wechat', displayName: '合成测试账号', status: 'online', upstreamConfigured: true, capabilities: { text: { status: 'unverified', reason: '接口尚待实际验收' }, image: { status: 'unsupported' }, history: { status: 'supported' } } }
  const conversation = { id: 'test-conversation', accountId: account.id, platform: 'wechat', title: '合成测试会话', kind: 'direct', unreadCount: 0 }
  await page.route('**/api/v1/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/session')) return route.fulfill({ json: { authenticated: true, csrfToken: 'synthetic-browser-test' } })
    if (path.endsWith('/accounts')) return route.fulfill({ json: { items: [account], nextCursor: null } })
    if (path.endsWith('/conversations')) return route.fulfill({ json: { items: [conversation], nextCursor: null } })
    if (path.endsWith('/read')) return route.fulfill({ status: 204 })
    if (path.endsWith('/events')) return route.fulfill({ contentType: 'text/event-stream', body: ': synthetic test\n\n' })
    if (path.endsWith('/messages') && route.request().method() === 'POST') { sends++; expect(route.request().headers()['x-csrf-token']).toBe('synthetic-browser-test'); expect(route.request().headers()['idempotency-key']).toBeTruthy(); return route.abort('failed') }
    if (path.endsWith('/messages')) { histories++; return route.fulfill({ json: { items: [{ id: 'unsafe-card', conversationId: conversation.id, accountId: account.id, platform: 'wechat', senderName: '测试联系人', direction: 'incoming', status: 'received', segments: [{ type: 'miniApp', title: '不安全链接样例', url: 'javascript:alert(1)' }, { type: 'image', url: 'https://example.com/tracking.png' }] }], nextCursor: null } }) }
    return route.fulfill({ status: 404, json: { error: { code: 'not_found', message: 'No test fixture' } } })
  })
  await page.goto('/')
  await page.locator('.conversation-item').click()
  const input = page.locator('.composer textarea')
  const send = page.getByRole('button', { name: '验证发送', exact: true })
  await expect(page.locator('.verification-notice')).toContainText('实际提交')
  await expect(page.locator('a[href^="javascript:"]')).toHaveCount(0)
  await expect(page.locator('img[src^="https://example.com"]')).toHaveCount(0)
  await input.fill('中'.repeat(5500))
  await expect(send).toBeDisabled()
  await expect(page.locator('.composer .inline-error')).toContainText('UTF-8')
  await input.fill('一次人工验证发送')
  await send.click()
  await expect(page.locator('.delivery-warning')).toContainText('结果待确认')
  await expect(input).toHaveValue('一次人工验证发送')
  await expect(send).toBeDisabled()
  await page.waitForTimeout(400)
  expect(sends).toBe(1)
  const historyBefore = histories
  await page.getByRole('button', { name: '核对历史', exact: true }).click()
  await expect.poll(() => histories).toBeGreaterThan(historyBefore)
  expect(sends).toBe(1)
})
